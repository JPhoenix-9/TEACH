import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const A='11111111-1111-4111-8111-111111111111',B='22222222-2222-4222-8222-222222222222',P='33333333-3333-4333-8333-333333333333';
test('student entitlements, ownership, expiration, verified school cap and repeat-school accounting',async()=>{const db=new PGlite();try{
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create schema extensions;
 create table auth.users(id uuid primary key);insert into auth.users values('${A}'),('${B}');
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema public,auth to authenticated,service_role;
 create table public.teach_administrators(user_id uuid primary key);insert into teach_administrators values('${A}');
 -- PGlite does not ship pgcrypto. A deterministic HMAC stand-in exercises authorization/transactions;
 -- actual pgcrypto HMAC compatibility is checked separately against the connected Postgres server.
 create function extensions.hmac(bytea,bytea,text) returns bytea language sql immutable as $$select decode('aaaa','hex')$$;
 `);
 await db.exec(readFileSync(new URL('../supabase/transcript-architect.sql',import.meta.url),'utf8'));
 await db.exec("insert into teach_transcript_private.configuration(signing_key) values('fixture-key')");
 await db.exec(`set role authenticated;select set_config('request.jwt.claim.sub','${B}',false)`);
 await assert.rejects(db.query('select create_transcript_staff_license()'),/Administrator/);
 await assert.rejects(db.exec(`insert into transcript_licenses(user_id) values('${B}')`),/permission denied/);
 await db.exec(`select set_config('request.jwt.claim.sub','${A}',false)`);
 const id=(await db.query('select create_transcript_staff_license() id')).rows[0].id;
 await db.query('select bind_transcript_project($1,$2)',[id,P]);await db.query('select bind_transcript_project($1,$2)',[id,P]);
 await assert.rejects(db.query('select bind_transcript_project($1,$2)',[id,B]),/already associated/);
 await db.query('select reserve_transcript_request($1,$2)',[id,P]);await assert.rejects(db.query('select reserve_transcript_request($1,$2)',[id,P]),/pause/);
 const expiry=Math.floor(Date.now()/1000)+600;
 const commit=async(key,signature='aaaa')=>(await db.query('select commit_transcript_school($1,$2,$3,$4,$5,$6) n',[A,id,P,key,expiry,signature])).rows[0].n;
 await assert.rejects(commit('forged.edu','bbbb'),/Verified school/);
 for(let i=0;i<12;i++)assert.equal(await commit(`school${i}.edu`),i+1);
 assert.equal(await commit('school0.edu'),12,'rechecking an institution does not use another slot');
 await assert.rejects(commit('school13.edu'),/All 12/);
 await db.exec(`select set_config('request.jwt.claim.sub','${B}',false)`);
 assert.equal((await db.query('select count(*)::int n from transcript_licenses')).rows[0].n,0);
 assert.equal((await db.query('select count(*)::int n from transcript_schools')).rows[0].n,0);
 await assert.rejects(db.query('select reserve_transcript_request($1,$2)',[id,P]),/active purchase/);
 await assert.rejects(commit('other.edu'),/verification expired/);
 for(const q of ['select * from teach_transcript_private.configuration','select * from transcript_requests',`update transcript_licenses set expires_at=now()+interval '10 years'`])await assert.rejects(db.exec(q),/permission denied/);
 await db.exec(`reset role;update transcript_licenses set expires_at=now()-interval '1 day',purchased_at=now()-interval '3 years' where id='${id}';set role authenticated;select set_config('request.jwt.claim.sub','${A}',false)`);
 await assert.rejects(db.query('select reserve_transcript_request($1,$2)',[id,P]),/active purchase/);
 }finally{await db.close();}});
