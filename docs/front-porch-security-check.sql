-- Transactional integration test: no test users or messages are committed.
begin;
do $$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); c uuid:=gen_random_uuid(); owner_id uuid;
 shared_id uuid; private_id uuid; reply_id uuid; blocked boolean;
begin
 select user_id into owner_id from public.teach_administrators limit 1;
 if owner_id is null then raise exception 'Owner missing'; end if;
 insert into auth.users(id) values(a),(b),(c);
 insert into public.family_profiles(user_id,parent_name) values(a,'Alpha Parent'),(b,'Beta Parent'),(c,'Planner Parent');
 insert into public.product_access(user_id,product_key) values(a,'blueprint'),(b,'gap-k2');
 perform set_config('request.jwt.claim.sub',a::text,true);
 execute 'set local role authenticated';
 if not private.porch_member() then raise exception 'Blueprint denied'; end if;
 insert into public.porch_threads(channel,user_id,title,body,author_name,author_staff) values('support',a,'Integration check','Shared fixture','Impersonated',true) returning id into shared_id;
 if not exists(select 1 from public.porch_threads where id=shared_id and author_name='Alpha' and not author_staff) then raise exception 'Identity stamp failed'; end if;
 execute 'reset role';
 update public.porch_threads set created_at=now()-interval '1 minute' where id=shared_id;
 execute 'set local role authenticated';
 insert into public.porch_threads(channel,user_id,title,body) values('ask-jana',a,'Private check','Private fixture') returning id into private_id;
 perform set_config('request.jwt.claim.sub',b::text,true);
 if not private.porch_member() then raise exception 'GAP denied'; end if;
 if (select count(*) from public.porch_threads where id=shared_id)<>1 then raise exception 'Shared not visible'; end if;
 if exists(select 1 from public.porch_threads where id=private_id) then raise exception 'Private thread leaked'; end if;
 blocked:=false;
 begin insert into public.porch_replies(thread_id,user_id,body) values(private_id,b,'Unauthorized reply'); exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Private reply permitted'; end if;
 blocked:=false;
 begin update public.porch_threads set title='Tampered' where id=shared_id; exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Immutable content editable'; end if;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 if not private.porch_staff() then raise exception 'Owner denied'; end if;
 insert into public.porch_replies(thread_id,user_id,body) values(private_id,owner_id,'Private owner reply') returning id into reply_id;
 perform set_config('request.jwt.claim.sub',a::text,true);
 if not exists(select 1 from public.porch_replies where id=reply_id) then raise exception 'Owner reply not visible to starter'; end if;
 perform set_config('request.jwt.claim.sub',b::text,true);
 if exists(select 1 from public.porch_replies where id=reply_id) then raise exception 'Private reply leaked'; end if;
 perform set_config('request.jwt.claim.sub',c::text,true);
 if private.porch_member() then raise exception 'Nonpurchaser accepted'; end if;
 if exists(select 1 from public.porch_threads) or exists(select 1 from public.porch_replies) then raise exception 'Nonpurchaser read messages'; end if;
 blocked:=false;
 begin insert into public.porch_threads(channel,user_id,title,body) values('support',c,'Denied','Denied'); exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Nonpurchaser write allowed'; end if;
 execute 'reset role';
 update public.product_access set revoked_at=now() where user_id=a;
 perform set_config('request.jwt.claim.sub',a::text,true);
 execute 'set local role authenticated';
 if private.porch_member() or exists(select 1 from public.porch_threads) then raise exception 'Revoked purchaser retained access'; end if;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 update public.porch_threads set hidden=true where id=shared_id;
 perform set_config('request.jwt.claim.sub',b::text,true);
 if exists(select 1 from public.porch_threads where id=shared_id) then raise exception 'Hidden thread exposed'; end if;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 update public.porch_threads set hidden=false where id=shared_id;
 perform set_config('request.jwt.claim.sub',b::text,true);
 if not exists(select 1 from public.porch_threads where id=shared_id) then raise exception 'Restore failed'; end if;
 execute 'reset role';
 execute 'set local role anon';
 blocked:=false;
 begin perform 1 from public.porch_threads; exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Anonymous read permitted'; end if;
 execute 'reset role';
end;
$$;
rollback;
